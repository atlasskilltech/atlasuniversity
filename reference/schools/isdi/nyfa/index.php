      if (!track) return;
      const originals = [...track.children];
      const oneCopyWidth = originals.reduce((s, el) => s + el.offsetWidth, 0);
      if (!oneCopyWidth) return;
      const targetWidth = track.parentElement.offsetWidth + oneCopyWidth;
