    const prev = document.querySelector(prevSel);
    const next = document.querySelector(nextSel);

    function move(dir) {
      if (sliderEl.swiper) {
        dir > 0 ? sliderEl.swiper.slideNext() : sliderEl.swiper.slidePrev();
        return;
      }
      // fallback if no swiper instance
      const card = wrap.querySelector('.swiper-slide');
      const amount = card ? card.offsetWidth + 20 : 320;
      wrap.scrollBy({ left: dir * amount, behavior: 'smooth' });
    }

    if (next) next.addEventListener('click', () => move(1));
    if (prev) prev.addEventListener('click', () => move(-1));
  }

  setTimeout(function () {
    const fulls = document.querySelectorAll('.common-swiper-full');
    // fulls[0] = Think International, fulls[1] = Voices, fulls[2] = Our Student Experiences
    setupArrows(fulls[1], '.voices-prev', '.voices-next');
    setupArrows(fulls[2], '.experiences-prev', '.experiences-next');
  }, 1200);
});
